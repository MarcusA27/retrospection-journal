#!/usr/bin/env python3
"""Auto-generate over-time weekly mirrors into journal/mirrors/ — the self-healing counterpart to
daily.py's catch-up.

For each COMPLETED week (never the in-progress one) in a recent window, writes a mirror covering that
week's active days if one doesn't already exist, and supersedes any stale/partial mirror for the same
ISO week — e.g. one generated by hand mid-week, before the later days existed. Idempotent: a week that
already has its final mirror costs no API calls. Each mirror is titled with a one-line essence.

Source is Claude Code transcripts by default (same as the nightly daily entry); pass an export dir to
include desktop history.

Usage:
  ./Scripts/weekly.py                       # ensure recent completed weeks have mirrors
  ./Scripts/weekly.py <export-dir> --weeks 6
"""
import argparse
import pathlib
import sys
from collections import defaultdict
from datetime import datetime, timedelta

import anthropic

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import sources  # noqa: E402
import mirror   # noqa: E402

RATE = {"claude-opus-4-8": (5, 25), "claude-sonnet-4-6": (3, 15), "claude-haiku-4-5": (1, 5)}

ESSENCE_SYSTEM = """You are titling one week's "mirror" — a reflection of how someone's thinking \
moved across a span of days. Given the mirror below, write its ESSENCE: one specific line, in the \
writer's terse voice, naming what the span was really about — the throughline, not a summary. A sharp \
phrase or a short real fragment from it. Never generic ("A Week of Reflection", "Growth", "Change"). \
No quotes, no label, no markdown, no trailing period. Output only that one line."""


def iso_of(date_str):
    return datetime.strptime(date_str, "%Y-%m-%d").isocalendar()[:2]


def main():
    mirror.load_env()
    ap = argparse.ArgumentParser(description="Auto-generate weekly mirrors for completed weeks.")
    ap.add_argument("export", nargs="?", help="claude.ai export dir/conversations.json (optional)")
    ap.add_argument("--weeks", type=int, default=3, help="how many recent completed weeks to ensure")
    ap.add_argument("--min-msgs", type=int, default=8, help="skip a week with fewer messages than this")
    ap.add_argument("--no-claude-code", action="store_true")
    ap.add_argument("--projects-dir")
    ap.add_argument("--model", default="claude-opus-4-8")
    ap.add_argument("--effort", default="high", choices=["low", "medium", "high", "max"])
    args = ap.parse_args()

    tz = datetime.now().astimezone().tzinfo
    today = datetime.strptime(sources.logical_date(datetime.now().astimezone(tz)), "%Y-%m-%d")
    today_iso = today.isocalendar()[:2]
    lo_date = (today - timedelta(weeks=args.weeks + 1)).strftime("%Y-%m-%d")
    hi_date = today.strftime("%Y-%m-%d")

    by_day_all = sources.collect(lo_date, hi_date, tz, export_path=args.export,
                                 include_claude_code=not args.no_claude_code, projects_dir=args.projects_dir)
    weeks = defaultdict(dict)
    for d, items in by_day_all.items():
        weeks[iso_of(d)][d] = items

    out_dir = pathlib.Path(sources.journal_dir()) / "mirrors"
    out_dir.mkdir(parents=True, exist_ok=True)
    # Weeks that already have ANY mirror — never regenerate or replace these. This is what keeps a
    # nightly run (Claude Code only) from clobbering a historical mirror built from the richer export.
    covered = set()
    for f in out_dir.glob("mirror-*.md"):
        parts = f.stem.replace("mirror-", "").split("_")
        if len(parts) == 2:
            try:
                covered.add(iso_of(parts[0]))
            except ValueError:
                pass

    client = anthropic.Anthropic()
    ci, co = RATE.get(args.model, (5, 25))

    made = 0
    for iso in sorted(weeks):
        if iso >= today_iso:
            continue   # the in-progress (or future) week isn't done — leave its days as loose buckets
        if iso in covered:
            continue   # already has a mirror — leave it alone (never thin a richer existing one)
        by_day = weeks[iso]
        dates = sorted(by_day)
        lo, hi = dates[0], dates[-1]
        n = sum(len(v) for v in by_day.values())
        if n < args.min_msgs:
            continue

        body, _ = mirror.render_messages(by_day)
        user = f"Window: {lo} to {hi}. {n} of your messages, across {len(by_day)} days.\n\n{body}"
        resp = client.messages.create(
            model=args.model, max_tokens=4000,
            thinking={"type": "adaptive"}, output_config={"effort": args.effort},
            system=mirror.SYSTEM, messages=[{"role": "user", "content": user}])
        text = "".join(b.text for b in resp.content if b.type == "text").strip()

        er = client.messages.create(
            model=args.model, max_tokens=80,
            thinking={"type": "adaptive"}, output_config={"effort": "low"},
            system=ESSENCE_SYSTEM, messages=[{"role": "user", "content": text}])
        essence = "".join(b.text for b in er.content if b.type == "text").strip()
        essence = essence.split("\n")[0].strip().strip('"').lstrip("# ").rstrip(".").strip()

        (out_dir / f"mirror-{lo}_{hi}.md").write_text(f"# {essence}\n\n{text}\n")
        covered.add(iso)
        made += 1
        u = resp.usage
        cost = u.input_tokens / 1e6 * ci + u.output_tokens / 1e6 * co
        print(f"✓ {lo}..{hi}  {n} msgs  ${cost:.3f}  —  {essence}", file=sys.stderr)

    print(f"[weekly] {made} mirror(s) written.", file=sys.stderr)


if __name__ == "__main__":
    main()
